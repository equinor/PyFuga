"""preluts.py
===========
Manage and cache preliminary look-up tables (preLUTs) as xarray datasets.

This module provides dataset wrappers for preLUTs generated by
:mod:`pyfuga.preluts_generator`. It handles I/O (loading from Fortran binary
files or saving to NetCDF), caching, and the aggregation of multiple
preLUTs into a combined dataset for use by :mod:`pyfuga.flut`.

Main classes:
    - :class:`PreLUT`: Single preLUT for a given (zeta0, kz0, beta) combination.
    - :class:`PreLUTs`: Aggregated collection of preLUTs across parameter ranges.
"""

from __future__ import annotations

from collections.abc import Iterator
from pathlib import Path
from typing import Any, cast

import numpy as np
import numpy.typing as npt
import xarray as xr
from tqdm import tqdm

from pyfuga.file_readers import read_pre_file, read_prelut_list
from pyfuga.utils import ComplexXRDataset, multiprocessing_map, normalise_n_cpu_workers, read_complex


class PreLUT(ComplexXRDataset):  # type: ignore[no-untyped-call]
    __slots__: list[str] = []

    @staticmethod
    def from_pre_file(
        filename: str | Path,
        zeta0: float,
        kz0: float | None = None,
        beta: float | None = None,
        kzmax: float | None = None,
        ds: float | None = None,
        accgoal: float | None = None,
    ) -> PreLUT:
        filename = Path(filename)
        if None in [kz0, beta, kzmax, ds, accgoal]:
            lut_meta = read_prelut_list(filename.parent, dict=True)
            assert isinstance(lut_meta, dict)
            ds_t, _smaxx, kz0, beta, kzmax, accgoal = lut_meta[filename.name]

            ds = ds_t
        assert kz0 is not None and beta is not None and kzmax is not None and ds is not None and accgoal is not None

        pre_file = read_pre_file(filename)
        return PreLUT(
            {**pre_file, "beta": beta, "kz0": kz0}, attrs={"ds": ds, "kzmax": kzmax, "zeta0": zeta0, "accgoal": accgoal}
        )

    @staticmethod
    def make_prelut(zeta0: float, kz0: float, beta: float, kzmax: float, ds: float, accgoal: float) -> PreLUT:
        from pyfuga.preluts_generator import PreLUTGenerator

        return PreLUTGenerator(zeta0, kz0, beta, kzmax, ds, accgoal).make_prelut()

    @staticmethod
    def make_prelut_args(args: tuple[Any, ...]) -> PreLUT:
        from pyfuga import utils

        jit = args[-1]
        rest = args[:-1]
        utils.compile(bool(jit))
        return PreLUT.make_prelut(*rest)


class PreLUTs(ComplexXRDataset):  # type: ignore[no-untyped-call]
    __slots__: list[str] = []

    @staticmethod
    def from_pre_files(folder: str | Path, zeta0: float, all_vars: bool = True, verbose: bool = True) -> PreLUTs:

        folder = Path(folder)

        fn, ds, smaxx, kz0, beta, kzmax, accgoal = list(zip(*read_prelut_list(folder, dict=False), strict=True))
        assert all(ds[0] == np.array(ds))
        assert all(kzmax[0] == np.array(kzmax))
        dat_lst = [read_pre_file(folder / f) for f in tqdm(fn, disable=(not verbose))]

        # ds, smaxx, kz0, beta, kzmax, accgoal
        nkz0 = len(np.unique(kz0))
        kz0_lst = np.array(kz0)[:nkz0]
        beta_lst = np.array(beta)[::nkz0]
        f = dat_lst[0]  # first
        n_node = np.array([len(d["level"][1]) for d in dat_lst])
        max_nodes = n_node.max()

        def get_var(k: str) -> tuple[list[str], npt.NDArray[Any]]:
            dim = ["beta", "kz0"] + f[k][0]
            shape = f[k][1].shape
            data = np.reshape(
                [np.r_[d[k][1], np.full((max_nodes - d[k][1].shape[0],) + shape[1:], np.nan)] for d in dat_lst],
                (len(beta_lst), nkz0, max_nodes) + shape[1:],
            )
            return (dim, data)

        if all_vars:
            var_name_lst: list[str] = list(f.keys())
        else:
            var_name_lst = [
                "Y_lower",
                "R_lower",
                "R_upper",
                "dbx_const",
                "dbx_lin",
                "dby_const",
                "dby_lin",
                "level",
            ]

        try:
            dim_dat_dict = {k: get_var(k) for k in var_name_lst}
        except KeyError:
            var_name_lst = ["Yleft", "Rleft", "Rright", "dyxu0", "dyxu1", "dyxv0", "dyxv1", "level"]
            dim_dat_dict = {k: get_var(k) for k in var_name_lst}
        return PreLUTs(
            {**dim_dat_dict},
            coords={"kz0": kz0_lst, "beta": beta_lst, "i": range(max_nodes)},
            attrs={"ds": ds[0], "kzmax": kzmax[0], "zeta0": zeta0, "accgoal": accgoal},
        )

    @staticmethod
    def make_preluts(
        zeta0: float,
        kz0_lst: npt.NDArray[np.float64] | list[float],
        beta_lst: npt.NDArray[np.float64] | list[float],
        kzmax: float,
        ds: float,
        accgoal: float,
        jit: bool = True,
        n_cpu: int | None = None,
        verbose: bool = True,
        compact: bool = True,
    ) -> PreLUTs | CompactPreLUTs:
        workers = normalise_n_cpu_workers(n_cpu)
        args_lst = [(zeta0, kz0, beta, kzmax, ds, accgoal, jit) for beta in beta_lst for kz0 in kz0_lst]

        iterator: Iterator[PreLUT]
        if workers == 1:
            iterator = map(PreLUT.make_prelut_args, args_lst)
            ds_lst = list(
                tqdm(
                    iterator,
                    total=len(args_lst),
                    disable=(not verbose),
                    desc="Generating preluts",
                )
            )
        else:
            with multiprocessing_map(workers, chunksize=1) as map_func:
                iterator = map_func(PreLUT.make_prelut_args, args_lst)
                ds_lst = list(
                    tqdm(
                        iterator,
                        total=len(args_lst),
                        disable=(not verbose),
                        desc="Generating preluts",
                    )
                )

        f = ds_lst[0]  # first
        for k in ["ds", "kzmax", "zeta0"]:
            assert all(f.attrs[k] == np.array([ds.attrs[k] for ds in ds_lst]))

        if compact:

            data_dict: dict[str, list[npt.NDArray[Any]]] = {}

            def collect(ds: PreLUT) -> None:
                for raw_k, v in ds.items():
                    k = str(raw_k)
                    if k not in data_dict:
                        data_dict[k] = []
                    if len(v.dims) and v.dims[0] == "i":
                        data_dict[k].append(v.values)
                    else:
                        data_dict[k].append(np.full(len(ds.i), v))

            while len(ds_lst):
                collect(ds_lst.pop())

            merged_vars: dict[str, tuple[tuple[str, ...], npt.NDArray[Any]]] = {}
            for k, v in data_dict.items():
                dim_tail = tuple(str(d) for d in f[k].dims[1:])
                merged_vars[k] = (("kz0_beta_i",) + dim_tail, np.concatenate(v, 0))

            return CompactPreLUTs(
                merged_vars,
                attrs={
                    "ds": f.ds,
                    "kzmax": f.kzmax,
                    "zeta0": f.zeta0,
                    "accgoal": f.accgoal,
                    "kz0_lst": kz0_lst,
                    "beta_lst": beta_lst,
                },
            )
        else:
            preluts = xr.combine_by_coords(
                [ds.assign_coords(i=ds.i, kz0=ds.kz0, beta=ds.beta).expand_dims(("kz0", "beta")) for ds in ds_lst]
            )

            return PreLUTs(
                preluts.data_vars,
                coords=preluts.coords,
                attrs={
                    "ds": f.ds,
                    "kzmax": f.kzmax,
                    "zeta0": f.zeta0,
                    "accgoal": f.accgoal,
                },
            )

    @classmethod
    def from_netcdf(cls, filename: str | Path) -> PreLUTs | CompactPreLUTs:
        ds = read_complex(filename)
        if "kz0_beta_i" in ds.dims:
            return CompactPreLUTs(ds.data_vars, coords=ds.coords, attrs=ds.attrs)
        else:
            return PreLUTs(ds.data_vars, coords=ds.coords, attrs=ds.attrs)


class CompactPreLUTs(PreLUTs):  # type: ignore[no-untyped-call]
    __slots__: list[str] = []

    def sel(
        self,
        indexers: Any = None,
        method: Any = None,
        tolerance: Any = None,
        drop: bool = False,
        kz0: float | None = None,
        beta: float | None = None,
        **indexers_kwargs: Any,
    ) -> PreLUTs:
        m = (self.beta.values == beta) & (self.kz0.values == kz0)
        ds = PreLUTs(
            {k: (("i",) + v.dims[1:], v.values[m]) for k, v in self.items()},
            attrs={k: v for k, v in self.attrs.items() if k not in ["kz0_lst", "beta_lst"]},
        )
        ds = ds.assign_coords(i=ds.i, beta=beta, kz0=kz0)
        return cast(
            PreLUTs,
            PreLUTs.sel(ds, indexers=indexers, method=method, tolerance=tolerance, drop=drop, **indexers_kwargs),
        )
